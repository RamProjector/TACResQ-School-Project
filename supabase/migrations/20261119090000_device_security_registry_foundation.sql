BEGIN;

-- Device identity is an additional risk signal, never an authentication factor.
-- All device writes will be mediated by trusted server-side verification.
CREATE TABLE IF NOT EXISTS public.user_devices (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  profile_id bigint NOT NULL REFERENCES public.profiles(id) ON DELETE RESTRICT,
  device_uid uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  device_name text NOT NULL DEFAULT 'Unknown device'
    CHECK (char_length(device_name) BETWEEN 1 AND 80),
  platform text NOT NULL CHECK (platform IN ('android', 'ios', 'web')),
  device_model text,
  app_version text,
  public_key text NOT NULL,
  key_algorithm text NOT NULL CHECK (key_algorithm IN ('Ed25519', 'ES256')),
  trust_status text NOT NULL DEFAULT 'pending'
    CHECK (trust_status IN ('pending', 'active', 'restricted', 'revoked')),
  registered_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  last_seen_at timestamptz,
  last_verified_at timestamptz,
  revoked_at timestamptz,
  revoked_by bigint REFERENCES public.profiles(id) ON DELETE SET NULL,
  revoked_reason text,
  CONSTRAINT user_devices_id_profile_unique UNIQUE (id, profile_id),
  CONSTRAINT user_devices_revocation_consistency CHECK (
    (trust_status = 'revoked' AND revoked_at IS NOT NULL)
    OR (trust_status <> 'revoked' AND revoked_at IS NULL)
  )
);

CREATE INDEX IF NOT EXISTS user_devices_profile_status_idx
  ON public.user_devices (profile_id, trust_status, last_seen_at DESC);

CREATE TABLE IF NOT EXISTS public.device_sessions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  device_id uuid NOT NULL REFERENCES public.user_devices(id) ON DELETE RESTRICT,
  profile_id bigint NOT NULL REFERENCES public.profiles(id) ON DELETE RESTRICT,
  auth_session_id uuid NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  last_seen_at timestamptz,
  expires_at timestamptz,
  revoked_at timestamptz,
  revoked_by bigint REFERENCES public.profiles(id) ON DELETE SET NULL,
  revoke_reason text,
  CONSTRAINT device_sessions_device_owner_fk
    FOREIGN KEY (device_id, profile_id)
    REFERENCES public.user_devices(id, profile_id) ON DELETE RESTRICT,
  CONSTRAINT device_sessions_revocation_consistency CHECK (
    (revoked_at IS NULL AND revoke_reason IS NULL)
    OR (revoked_at IS NOT NULL AND revoke_reason IS NOT NULL)
  )
);

CREATE INDEX IF NOT EXISTS device_sessions_profile_active_idx
  ON public.device_sessions (profile_id, last_seen_at DESC)
  WHERE revoked_at IS NULL;

CREATE INDEX IF NOT EXISTS device_sessions_device_active_idx
  ON public.device_sessions (device_id, last_seen_at DESC)
  WHERE revoked_at IS NULL;

-- Store only a hash of a one-time challenge. The raw challenge is returned once
-- by the trusted verifier and must never be persisted in this table or logs.
CREATE TABLE IF NOT EXISTS public.device_challenges (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  profile_id bigint NOT NULL REFERENCES public.profiles(id) ON DELETE RESTRICT,
  device_id uuid REFERENCES public.user_devices(id) ON DELETE RESTRICT,
  auth_session_id uuid,
  purpose text NOT NULL CHECK (purpose IN ('registration', 'session_proof', 'step_up')),
  challenge_hash text NOT NULL UNIQUE
    CHECK (challenge_hash ~ '^[0-9a-f]{64}$'),
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  expires_at timestamptz NOT NULL,
  consumed_at timestamptz,
  CONSTRAINT device_challenges_device_owner_fk
    FOREIGN KEY (device_id, profile_id)
    REFERENCES public.user_devices(id, profile_id) ON DELETE RESTRICT,
  CONSTRAINT device_challenges_expiry_check CHECK (expires_at > created_at),
  CONSTRAINT device_challenges_consumption_check CHECK (
    consumed_at IS NULL OR consumed_at >= created_at
  )
);

CREATE INDEX IF NOT EXISTS device_challenges_expiry_idx
  ON public.device_challenges (expires_at)
  WHERE consumed_at IS NULL;

-- Append-only event stream. Sensitive payloads and raw attestation tokens,
-- signatures, access tokens, and private keys must never be stored here.
CREATE TABLE IF NOT EXISTS public.device_security_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  profile_id bigint REFERENCES public.profiles(id) ON DELETE SET NULL,
  device_id uuid REFERENCES public.user_devices(id) ON DELETE SET NULL,
  auth_session_id uuid,
  event_type text NOT NULL CHECK (event_type IN (
    'registration_requested',
    'registration_verified',
    'registration_rejected',
    'proof_verified',
    'proof_rejected',
    'integrity_passed',
    'integrity_failed',
    'device_revoked',
    'session_revoked',
    'step_up_required',
    'suspicious_activity'
  )),
  severity text NOT NULL DEFAULT 'info'
    CHECK (severity IN ('info', 'warning', 'high', 'critical')),
  details jsonb NOT NULL DEFAULT '{}'::jsonb
    CHECK (jsonb_typeof(details) = 'object'),
  created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE INDEX IF NOT EXISTS device_security_events_profile_created_idx
  ON public.device_security_events (profile_id, created_at DESC);

CREATE INDEX IF NOT EXISTS device_security_events_device_created_idx
  ON public.device_security_events (device_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.device_integrity_checks (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  profile_id bigint NOT NULL REFERENCES public.profiles(id) ON DELETE RESTRICT,
  device_id uuid NOT NULL REFERENCES public.user_devices(id) ON DELETE RESTRICT,
  provider text NOT NULL CHECK (provider IN ('play_integrity', 'app_attest', 'web_authn', 'server_key_proof')),
  verdict text NOT NULL CHECK (verdict IN ('pass', 'fail', 'unknown', 'not_supported')),
  app_recognized boolean,
  device_integrity boolean,
  app_access_risk text,
  verifier_version text NOT NULL,
  result_summary jsonb NOT NULL DEFAULT '{}'::jsonb
    CHECK (jsonb_typeof(result_summary) = 'object'),
  checked_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  CONSTRAINT device_integrity_checks_device_owner_fk
    FOREIGN KEY (device_id, profile_id)
    REFERENCES public.user_devices(id, profile_id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS device_integrity_checks_device_checked_idx
  ON public.device_integrity_checks (device_id, checked_at DESC);

-- Keep the entire registry backend-only until server verification endpoints,
-- authorization rules, and runtime contract tests are reviewed and deployed.
ALTER TABLE public.user_devices ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.device_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.device_challenges ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.device_security_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.device_integrity_checks ENABLE ROW LEVEL SECURITY;

REVOKE ALL PRIVILEGES ON TABLE
  public.user_devices,
  public.device_sessions,
  public.device_challenges,
  public.device_security_events,
  public.device_integrity_checks
FROM PUBLIC, anon, authenticated, service_role;

GRANT SELECT, INSERT, UPDATE ON TABLE
  public.user_devices,
  public.device_sessions,
  public.device_challenges
TO service_role;

GRANT SELECT, INSERT ON TABLE
  public.device_security_events,
  public.device_integrity_checks
TO service_role;

GRANT USAGE, SELECT ON SEQUENCE
  public.device_security_events_id_seq,
  public.device_integrity_checks_id_seq
TO service_role;

COMMENT ON TABLE public.user_devices IS
  'Backend-managed per-install device registry. Device identifiers are not authentication.';
COMMENT ON TABLE public.device_sessions IS
  'Backend-managed association between Supabase auth sessions and registered device records.';
COMMENT ON TABLE public.device_challenges IS
  'Short-lived one-time device proof challenges; stores SHA-256 challenge hashes only.';
COMMENT ON TABLE public.device_security_events IS
  'Append-only backend-generated device security event history; do not store secrets or raw attestation tokens.';
COMMENT ON TABLE public.device_integrity_checks IS
  'Backend-verified device/app integrity summaries; never treat a verdict as sole proof of identity.';

COMMIT;

BEGIN;

-- Keep dispatcher claimability changes attributable to the RPC and actor.
CREATE TABLE IF NOT EXISTS public.incident_claimability_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- Store historical IDs without foreign keys so account/incident retention
  -- workflows are not blocked by audit history.
  incident_id bigint NOT NULL,
  actor_profile_id bigint,
  source_rpc text NOT NULL CHECK (source_rpc IN ('api_set_incident_claimable', 'incident_status_transition', 'migration_backfill')),
  previous_claimable boolean NOT NULL,
  new_claimable boolean NOT NULL,
  incident_status text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

ALTER TABLE public.incident_claimability_logs ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.incident_claimability_logs FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.incident_claimability_logs TO service_role;

CREATE INDEX IF NOT EXISTS incident_claimability_logs_incident_created_idx
  ON public.incident_claimability_logs (incident_id, created_at DESC);
CREATE INDEX IF NOT EXISTS incident_claimability_logs_actor_created_idx
  ON public.incident_claimability_logs (actor_profile_id, created_at DESC);

-- All supported Android and web clients write incidents through SECURITY DEFINER
-- RPCs. Remove direct authenticated DML so callers cannot bypass validation or
-- the claimability audit trail through the PostgREST table endpoint.
REVOKE INSERT, UPDATE, DELETE ON TABLE public.incidents FROM PUBLIC, anon, authenticated;

-- PostgreSQL column-level ACLs are independent of table-level ACLs. Remove
-- any historical per-column grants as well, or they would survive the table
-- revoke above (the live schema currently has column grants on status,
-- assigned_to, and updated_at).
DO $revoke_incident_column_grants$
DECLARE
  v_columns text;
BEGIN
  SELECT string_agg(format('%I', attname), ', ' ORDER BY attnum)
  INTO v_columns
  FROM pg_catalog.pg_attribute
  WHERE attrelid = 'public.incidents'::regclass
    AND attnum > 0
    AND NOT attisdropped;

  IF v_columns IS NOT NULL THEN
    EXECUTE format(
      'REVOKE INSERT (%1$s), UPDATE (%1$s) ON TABLE public.incidents FROM PUBLIC, anon, authenticated',
      v_columns
    );
  END IF;
END;
$revoke_incident_column_grants$;

CREATE OR REPLACE FUNCTION public.tacresq_clear_claimability_on_status_progress()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $function$
BEGIN
  IF NEW.status IN ('en_route', 'on_scene', 'transporting', 'resolved', 'cancelled', 'completed') THEN
    NEW.is_claimable := false;
  END IF;
  RETURN NEW;
END;
$function$;
REVOKE ALL ON FUNCTION public.tacresq_clear_claimability_on_status_progress() FROM PUBLIC, anon, authenticated;

-- The zzz_ prefix intentionally runs this BEFORE trigger after the existing
-- incident authorization/transition guard, so responders can advance status
-- without being treated as directly changing the dispatcher-owned flag.
DROP TRIGGER IF EXISTS zzz_tacresq_clear_claimability_on_status_progress ON public.incidents;
CREATE TRIGGER zzz_tacresq_clear_claimability_on_status_progress
BEFORE UPDATE OF status ON public.incidents
FOR EACH ROW
WHEN (OLD.status IS DISTINCT FROM NEW.status)
EXECUTE FUNCTION public.tacresq_clear_claimability_on_status_progress();

CREATE OR REPLACE FUNCTION public.tacresq_log_claimability_status_transition()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog
AS $function$
DECLARE
  v_actor_profile_id bigint;
BEGIN
  IF OLD.is_claimable IS TRUE AND NEW.is_claimable IS FALSE THEN
    SELECT id INTO v_actor_profile_id
    FROM public.profiles
    WHERE auth_user_id = auth.uid();

    INSERT INTO public.incident_claimability_logs (
      incident_id, actor_profile_id, source_rpc, previous_claimable,
      new_claimable, incident_status
    ) VALUES (
      NEW.id, v_actor_profile_id, 'incident_status_transition',
      OLD.is_claimable, NEW.is_claimable, NEW.status
    );
  END IF;
  RETURN NEW;
END;
$function$;
REVOKE ALL ON FUNCTION public.tacresq_log_claimability_status_transition() FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS tacresq_log_claimability_status_transition ON public.incidents;
CREATE TRIGGER tacresq_log_claimability_status_transition
AFTER UPDATE OF status ON public.incidents
FOR EACH ROW
WHEN (OLD.status IS DISTINCT FROM NEW.status)
EXECUTE FUNCTION public.tacresq_log_claimability_status_transition();

-- Repair legacy rows that remained marked claimable after dispatch progression.
WITH repaired AS (
  UPDATE public.incidents
  SET is_claimable = false,
      updated_at = clock_timestamp()
  WHERE status IN ('en_route', 'on_scene', 'transporting', 'resolved', 'cancelled', 'completed')
    AND is_claimable IS TRUE
  RETURNING id, status
)
INSERT INTO public.incident_claimability_logs (
  incident_id, actor_profile_id, source_rpc, previous_claimable,
  new_claimable, incident_status
)
SELECT id, NULL, 'migration_backfill', true, false, status
FROM repaired;

-- Serialize claimability changes with cancellation, completion, and field claims.
-- Lock order is incident -> dispatcher profile, matching the field-claim RPC.
CREATE OR REPLACE FUNCTION public.api_set_incident_claimable(
  p_incident_id bigint,
  p_claimable boolean
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog
AS $function$
DECLARE
  v_auth_uid uuid;
  v_actor public.profiles;
  v_actor_role text;
  v_incident public.incidents;
  v_previous_claimable boolean;
BEGIN
  v_auth_uid := auth.uid();
  IF v_auth_uid IS NULL THEN
    RAISE EXCEPTION 'Authentication required.' USING ERRCODE = '42501';
  END IF;

  IF p_incident_id IS NULL OR p_incident_id < 1 OR p_claimable IS NULL THEN
    RAISE EXCEPTION 'Incident and claimability values are required.' USING ERRCODE = '22023';
  END IF;

  -- Reject unauthorized callers before allowing them to contend on an incident row.
  SELECT role INTO v_actor_role
  FROM public.profiles
  WHERE auth_user_id = v_auth_uid;

  IF v_actor_role IS DISTINCT FROM 'dispatcher' THEN
    RAISE EXCEPTION 'Only dispatchers can toggle field claiming for incidents.' USING ERRCODE = '42501';
  END IF;

  -- Acquire the incident lock before checking state so a concurrent terminal
  -- transition cannot be followed by a stale claimability update.
  SELECT * INTO v_incident
  FROM public.incidents
  WHERE id = p_incident_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Incident not found.' USING ERRCODE = 'P0002';
  END IF;

  -- Lock and re-read the actor after the incident, using the same lock order as
  -- field claiming. This prevents a concurrent role change from authorizing a
  -- stale dispatcher profile.
  SELECT * INTO v_actor
  FROM public.profiles
  WHERE auth_user_id = v_auth_uid
  FOR UPDATE;

  IF v_actor.id IS NULL OR v_actor.role IS DISTINCT FROM 'dispatcher' THEN
    RAISE EXCEPTION 'Only dispatchers can toggle field claiming for incidents.' USING ERRCODE = '42501';
  END IF;

  IF p_claimable IS TRUE AND v_incident.status NOT IN ('pending', 'assigned') THEN
    RAISE EXCEPTION 'Only pending or assigned incidents can be made claimable.' USING ERRCODE = '22000';
  END IF;

  v_previous_claimable := v_incident.is_claimable;

  -- A no-op request should not touch updated_at or create audit noise.
  IF v_previous_claimable IS NOT DISTINCT FROM p_claimable THEN
    RETURN jsonb_build_object(
      'id', v_incident.id,
      'status', v_incident.status,
      'is_claimable', v_incident.is_claimable
    );
  END IF;

  UPDATE public.incidents
  SET is_claimable = p_claimable,
      updated_at = clock_timestamp()
  WHERE id = v_incident.id
  RETURNING * INTO v_incident;

  IF v_previous_claimable IS DISTINCT FROM v_incident.is_claimable THEN
    INSERT INTO public.incident_claimability_logs (
      incident_id, actor_profile_id, source_rpc, previous_claimable,
      new_claimable, incident_status
    ) VALUES (
      v_incident.id, v_actor.id, 'api_set_incident_claimable',
      v_previous_claimable, v_incident.is_claimable, v_incident.status
    );
  END IF;

  RETURN jsonb_build_object(
    'id', v_incident.id,
    'status', v_incident.status,
    'is_claimable', v_incident.is_claimable
  );
END;
$function$;

REVOKE ALL ON FUNCTION public.api_set_incident_claimable(bigint, boolean) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.api_set_incident_claimable(bigint, boolean) TO authenticated;

COMMIT;

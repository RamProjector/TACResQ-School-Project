CREATE OR REPLACE FUNCTION private.tacresq_can_access_incident_chat(
  p_incident_id bigint,
  p_actor_profile_id bigint
)
RETURNS boolean
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog
AS $function$
DECLARE
  actor_role text;
  incident_requester_id bigint;
BEGIN
  SELECT p.role::text, i.requester_id
    INTO actor_role, incident_requester_id
    FROM public.profiles p
    JOIN public.incidents i ON i.id = p_incident_id
   WHERE p.id = p_actor_profile_id;

  IF NOT FOUND THEN
    RETURN false;
  END IF;

  IF actor_role = 'dispatcher' THEN
    RETURN true;
  ELSIF actor_role = 'requester' THEN
    RETURN incident_requester_id = p_actor_profile_id;
  ELSIF actor_role IN ('responder', 'driver') THEN
    RETURN EXISTS (
      SELECT 1
        FROM public.incident_assignments a
       WHERE a.incident_id = p_incident_id
         AND a.user_id = p_actor_profile_id
    ) OR EXISTS (
      SELECT 1
        FROM public.incidents i
       WHERE i.id = p_incident_id
         AND i.assigned_to = p_actor_profile_id
    );
  END IF;

  -- Fail closed for unknown roles, including Admin unless a separate explicit
  -- policy is reviewed and added later.
  RETURN false;
END;
$function$;

REVOKE ALL ON FUNCTION private.tacresq_can_access_incident_chat(bigint, bigint) FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.api_my_incident_messages(
  p_incident_id bigint,
  p_limit integer DEFAULT 50,
  p_before_id bigint DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog
AS $function$
DECLARE
  actor_profile_id bigint;
BEGIN
  SELECT p.id
    INTO actor_profile_id
    FROM public.profiles p
   WHERE p.auth_user_id = auth.uid();

  IF actor_profile_id IS NULL THEN
    RAISE EXCEPTION 'Authenticated profile is required'
      USING ERRCODE = '42501';
  END IF;

  IF p_incident_id IS NULL OR p_incident_id < 1 THEN
    RAISE EXCEPTION 'Incident ID is invalid'
      USING ERRCODE = '22023';
  END IF;

  IF p_limit IS NULL OR p_limit < 1 OR p_limit > 100 THEN
    RAISE EXCEPTION 'Message page size must be between 1 and 100'
      USING ERRCODE = '22023';
  END IF;

  IF p_before_id IS NOT NULL AND p_before_id < 1 THEN
    RAISE EXCEPTION 'Message cursor is invalid'
      USING ERRCODE = '22023';
  END IF;

  IF NOT private.tacresq_can_access_incident_chat(p_incident_id, actor_profile_id) THEN
    RAISE EXCEPTION 'Incident chat is not available to this account'
      USING ERRCODE = '42501';
  END IF;

  RETURN (
    SELECT coalesce(
      jsonb_agg(
        jsonb_build_object(
          'id', page.id,
          'incident_id', page.incident_id,
          'sender_id', page.sender_id,
          'message', page.message,
          'created_at', page.created_at
        ) ORDER BY page.id ASC
      ),
      '[]'::jsonb
    )
    FROM (
      SELECT m.id, m.incident_id, m.sender_id, m.message, m.created_at
        FROM public.incident_messages m
       WHERE m.incident_id = p_incident_id
         AND (p_before_id IS NULL OR m.id < p_before_id)
       ORDER BY m.id DESC
       LIMIT p_limit
    ) AS page
  );
END;
$function$;

CREATE OR REPLACE FUNCTION public.api_send_incident_message(
  p_incident_id bigint,
  p_message text,
  p_client_message_id uuid
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog
AS $function$
DECLARE
  actor_profile_id bigint;
  normalized_message text;
  existing_message public.incident_messages%ROWTYPE;
  created_message public.incident_messages%ROWTYPE;
  recent_message_count integer;
BEGIN
  SELECT p.id
    INTO actor_profile_id
    FROM public.profiles p
   WHERE p.auth_user_id = auth.uid();

  IF actor_profile_id IS NULL THEN
    RAISE EXCEPTION 'Authenticated profile is required'
      USING ERRCODE = '42501';
  END IF;

  IF p_incident_id IS NULL OR p_incident_id < 1 THEN
    RAISE EXCEPTION 'Incident ID is invalid'
      USING ERRCODE = '22023';
  END IF;

  normalized_message := btrim(coalesce(p_message, ''));
  IF length(normalized_message) < 1 OR length(normalized_message) > 2000 THEN
    RAISE EXCEPTION 'Message must contain 1 to 2000 characters'
      USING ERRCODE = '22023';
  END IF;

  IF p_client_message_id IS NULL THEN
    RAISE EXCEPTION 'Client message ID is required for safe retries'
      USING ERRCODE = '22023';
  END IF;

  IF NOT private.tacresq_can_access_incident_chat(p_incident_id, actor_profile_id) THEN
    RAISE EXCEPTION 'Incident chat is not available to this account'
      USING ERRCODE = '42501';
  END IF;

  -- Serialize sends per sender before checking idempotency. This prevents
  -- concurrent retries with the same client key from racing into a unique error.
  PERFORM pg_advisory_xact_lock(actor_profile_id);

  -- An idempotent retry returns the original message. Reusing the same key for
  -- different content or a different incident is rejected.
  SELECT m.*
    INTO existing_message
    FROM public.incident_messages m
   WHERE m.sender_id = actor_profile_id
     AND m.client_message_id = p_client_message_id;

  IF FOUND THEN
    IF existing_message.incident_id <> p_incident_id
       OR existing_message.message <> normalized_message THEN
      RAISE EXCEPTION 'Client message ID was already used for different content'
        USING ERRCODE = '23505';
    END IF;
    RETURN jsonb_build_object(
      'id', existing_message.id,
      'incident_id', existing_message.incident_id,
      'sender_id', existing_message.sender_id,
      'message', existing_message.message,
      'created_at', existing_message.created_at
    );
  END IF;

  -- Apply the flood guard only to new messages, not to idempotent retries.
  SELECT count(*) INTO recent_message_count
    FROM public.incident_messages m
   WHERE m.sender_id = actor_profile_id
     AND m.created_at >= now() - interval '1 minute';
  IF recent_message_count >= 20 THEN
    RAISE EXCEPTION 'Message rate limit reached; wait before sending again'
      USING ERRCODE = '54000';
  END IF;

  INSERT INTO public.incident_messages (
    incident_id, sender_id, client_message_id, message
  ) VALUES (
    p_incident_id, actor_profile_id, p_client_message_id, normalized_message
  )
  RETURNING * INTO created_message;

  RETURN jsonb_build_object(
    'id', created_message.id,
    'incident_id', created_message.incident_id,
    'sender_id', created_message.sender_id,
    'message', created_message.message,
    'created_at', created_message.created_at
  );
END;
$function$;

REVOKE ALL ON FUNCTION public.api_my_incident_messages(bigint, integer, bigint) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.api_send_incident_message(bigint, text, uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.api_my_incident_messages(bigint, integer, bigint) TO authenticated;
GRANT EXECUTE ON FUNCTION public.api_send_incident_message(bigint, text, uuid) TO authenticated;

CREATE OR REPLACE FUNCTION private.tacresq_notify_incident_message_insert()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog
AS $function$
DECLARE
  recipient record;
BEGIN
  FOR recipient IN
    SELECT participant.profile_id
      FROM (
        SELECT i.requester_id AS profile_id
          FROM public.incidents i
         WHERE i.id = NEW.incident_id
        UNION
        SELECT a.user_id AS profile_id
          FROM public.incident_assignments a
         WHERE a.incident_id = NEW.incident_id
        UNION
        SELECT i.assigned_to AS profile_id
          FROM public.incidents i
         WHERE i.id = NEW.incident_id
      ) AS participant
     WHERE participant.profile_id IS NOT NULL
       AND participant.profile_id <> NEW.sender_id
  LOOP
    INSERT INTO public.user_notifications (
      recipient_user_id, incident_id, event_type, title, body
    ) VALUES (
      recipient.profile_id, NEW.incident_id, 'incident_message',
      'New incident message',
      'A participant sent a new message in an incident conversation.'
    );
  END LOOP;

  RETURN NEW;
END;
$function$;

REVOKE ALL ON FUNCTION private.tacresq_notify_incident_message_insert() FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS tacresq_notify_incident_message_insert ON public.incident_messages;
CREATE TRIGGER tacresq_notify_incident_message_insert
AFTER INSERT ON public.incident_messages
FOR EACH ROW EXECUTE FUNCTION private.tacresq_notify_incident_message_insert();

COMMIT;

CREATE TABLE IF NOT EXISTS public.user_notifications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipient_user_id bigint NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  incident_id bigint REFERENCES public.incidents(id) ON DELETE CASCADE,
  event_type text NOT NULL CHECK (event_type IN ('incident_assigned', 'incident_status_changed')),
  title text NOT NULL CHECK (length(btrim(title)) BETWEEN 1 AND 120),
  body text NOT NULL CHECK (length(btrim(body)) BETWEEN 1 AND 300),
  created_at timestamptz NOT NULL DEFAULT now(),
  read_at timestamptz
);

CREATE INDEX IF NOT EXISTS user_notifications_recipient_created_idx
  ON public.user_notifications (recipient_user_id, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS user_notifications_unread_idx
  ON public.user_notifications (recipient_user_id, created_at DESC)
  WHERE read_at IS NULL;
-- A team assignment can update incidents.assigned_to before inserting all assignment
-- rows. Both trigger paths may observe the same event; suppress duplicate unread
-- assignment alerts per recipient, while allowing a new alert after the old one is read.
CREATE UNIQUE INDEX IF NOT EXISTS user_notifications_one_unread_assignment_idx
  ON public.user_notifications (recipient_user_id, incident_id)
  WHERE event_type = 'incident_assigned' AND read_at IS NULL;
-- A team assignment can update incidents.assigned_to before inserting all assignment
-- rows. Both trigger paths may observe the same event; suppress duplicate unread
-- assignment alerts per recipient, while allowing a new alert after the old one is read.
CREATE UNIQUE INDEX IF NOT EXISTS user_notifications_one_unread_assignment_idx
  ON public.user_notifications (recipient_user_id, incident_id)
  WHERE event_type = 'incident_assigned' AND read_at IS NULL;

ALTER TABLE public.user_notifications ENABLE ROW LEVEL SECURITY;
-- Notifications are accessed only through narrowly scoped RPCs. Keep direct table
-- access closed, including direct writes that could forge another user's alerts.
REVOKE ALL ON TABLE public.user_notifications FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.user_notifications_id_seq FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION private.tacresq_notify_assignment_insert()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog
AS $function$
DECLARE
  requester_profile_id bigint;
  assigned_profile_name text;
BEGIN
  SELECT i.requester_id
    INTO requester_profile_id
    FROM public.incidents i
   WHERE i.id = NEW.incident_id;

  IF requester_profile_id IS NULL THEN
    RETURN NEW;
  END IF;

  INSERT INTO public.user_notifications (
    recipient_user_id, incident_id, event_type, title, body
  ) VALUES (
    NEW.user_id, NEW.incident_id, 'incident_assigned',
    'New incident assignment',
    'You have been assigned to an incident. Open TACResQ to review the details.'
  ) ON CONFLICT (recipient_user_id, incident_id)
    WHERE event_type = 'incident_assigned' AND read_at IS NULL
    DO NOTHING;

  INSERT INTO public.user_notifications (
    recipient_user_id, incident_id, event_type, title, body
  ) VALUES (
    requester_profile_id, NEW.incident_id, 'incident_assigned',
    'Response unit assigned',
    'A response unit has been assigned to your request.'
  ) ON CONFLICT (recipient_user_id, incident_id)
    WHERE event_type = 'incident_assigned' AND read_at IS NULL
    DO NOTHING;

  RETURN NEW;
END;
$function$;

REVOKE ALL ON FUNCTION private.tacresq_notify_assignment_insert() FROM PUBLIC, anon, authenticated;

-- The existing web dashboard still uses api_assign_incident. Cover that legacy
-- single-unit path as well, while avoiding duplicate alerts when the team RPC
-- has already inserted the matching incident_assignments row.
CREATE OR REPLACE FUNCTION private.tacresq_notify_legacy_assignment_update()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog
AS $function$
BEGIN
  IF NEW.assigned_to IS NULL THEN
    RETURN NEW;
  END IF;

  IF EXISTS (
    SELECT 1
      FROM public.incident_assignments a
     WHERE a.incident_id = NEW.id
       AND a.user_id = NEW.assigned_to
  ) THEN
    RETURN NEW;
  END IF;

  INSERT INTO public.user_notifications (
    recipient_user_id, incident_id, event_type, title, body
  ) VALUES (
    NEW.assigned_to, NEW.id, 'incident_assigned',
    'New incident assignment',
    'You have been assigned to an incident. Open TACResQ to review the details.'
  ) ON CONFLICT (recipient_user_id, incident_id)
    WHERE event_type = 'incident_assigned' AND read_at IS NULL
    DO NOTHING;

  INSERT INTO public.user_notifications (
    recipient_user_id, incident_id, event_type, title, body
  ) VALUES (
    NEW.requester_id, NEW.id, 'incident_assigned',
    'Response unit assigned',
    'A response unit has been assigned to your request.'
  ) ON CONFLICT (recipient_user_id, incident_id)
    WHERE event_type = 'incident_assigned' AND read_at IS NULL
    DO NOTHING;

  RETURN NEW;
END;
$function$;

REVOKE ALL ON FUNCTION private.tacresq_notify_legacy_assignment_update() FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION private.tacresq_notify_status_log_insert()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog
AS $function$
DECLARE
  incident_requester_id bigint;
  recipient record;
  notification_title text;
  notification_body text;
BEGIN
  -- Initial request creation and the assignment status are covered by the
  -- requester flow and assignment trigger respectively; avoid duplicate alerts.
  IF NEW.status IN ('pending', 'assigned') THEN
    RETURN NEW;
  END IF;

  SELECT i.requester_id
    INTO incident_requester_id
    FROM public.incidents i
   WHERE i.id = NEW.incident_id;

  IF incident_requester_id IS NULL THEN
    RETURN NEW;
  END IF;

  notification_title := 'Incident status updated';
  notification_body := 'The incident status is now ' || replace(NEW.status::text, '_', ' ') || '.';

  FOR recipient IN
    SELECT participant.profile_id
      FROM (
        SELECT incident_requester_id AS profile_id
        UNION
        SELECT a.user_id AS profile_id
          FROM public.incident_assignments a
         WHERE a.incident_id = NEW.incident_id
      ) AS participant
     WHERE participant.profile_id IS NOT NULL
       AND participant.profile_id IS DISTINCT FROM NEW.changed_by
  LOOP
    INSERT INTO public.user_notifications (
      recipient_user_id, incident_id, event_type, title, body
    ) VALUES (
      recipient.profile_id, NEW.incident_id, 'incident_status_changed',
      notification_title, notification_body
    );
  END LOOP;

  RETURN NEW;
END;
$function$;

REVOKE ALL ON FUNCTION private.tacresq_notify_status_log_insert() FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS tacresq_notify_assignment_insert ON public.incident_assignments;
CREATE TRIGGER tacresq_notify_assignment_insert
AFTER INSERT ON public.incident_assignments
FOR EACH ROW EXECUTE FUNCTION private.tacresq_notify_assignment_insert();

DROP TRIGGER IF EXISTS tacresq_notify_legacy_assignment_update ON public.incidents;
CREATE TRIGGER tacresq_notify_legacy_assignment_update
AFTER UPDATE OF assigned_to ON public.incidents
FOR EACH ROW
WHEN (NEW.assigned_to IS DISTINCT FROM OLD.assigned_to)
EXECUTE FUNCTION private.tacresq_notify_legacy_assignment_update();

DROP TRIGGER IF EXISTS tacresq_notify_status_log_insert ON public.incident_status_logs;
CREATE TRIGGER tacresq_notify_status_log_insert
AFTER INSERT ON public.incident_status_logs
FOR EACH ROW EXECUTE FUNCTION private.tacresq_notify_status_log_insert();

CREATE OR REPLACE FUNCTION public.api_my_notifications(p_limit integer DEFAULT 50)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog
AS $function$
DECLARE
  actor_profile_id bigint;
BEGIN
  SELECT p.id
    INTO actor_profile_id
    FROM public.profiles p
   WHERE p.auth_user_id = auth.uid();

  IF actor_profile_id IS NULL THEN
    RAISE EXCEPTION 'Authenticated profile is required'
      USING ERRCODE = '42501';
  END IF;

  IF p_limit IS NULL OR p_limit < 1 OR p_limit > 100 THEN
    RAISE EXCEPTION 'Notification page size must be between 1 and 100'
      USING ERRCODE = '22023';
  END IF;

  RETURN (
    SELECT coalesce(
      jsonb_agg(
        jsonb_build_object(
          'id', n.id,
          'incident_id', n.incident_id,
          'event_type', n.event_type,
          'title', n.title,
          'body', n.body,
          'created_at', n.created_at,
          'read_at', n.read_at
        ) ORDER BY n.created_at DESC, n.id DESC
      ),
      '[]'::jsonb
    )
    FROM (
      SELECT id, incident_id, event_type, title, body, created_at, read_at
        FROM public.user_notifications n
       WHERE n.recipient_user_id = actor_profile_id
       ORDER BY n.created_at DESC, n.id DESC
       LIMIT p_limit
    ) n
  );
END;
$function$;

CREATE OR REPLACE FUNCTION public.api_mark_notification_read(p_notification_id bigint)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog
AS $function$
DECLARE
  actor_profile_id bigint;
BEGIN
  SELECT p.id
    INTO actor_profile_id
    FROM public.profiles p
   WHERE p.auth_user_id = auth.uid();

  IF actor_profile_id IS NULL THEN
    RAISE EXCEPTION 'Authenticated profile is required'
      USING ERRCODE = '42501';
  END IF;

  IF p_notification_id IS NULL OR p_notification_id < 1 THEN
    RAISE EXCEPTION 'Notification ID is invalid'
      USING ERRCODE = '22023';
  END IF;

  UPDATE public.user_notifications
     SET read_at = coalesce(read_at, now())
   WHERE id = p_notification_id
     AND recipient_user_id = actor_profile_id;

  -- False means either not found or not owned by this caller; this avoids
  -- exposing whether another user's notification ID exists.
  RETURN FOUND;
END;
$function$;

REVOKE ALL ON FUNCTION public.api_my_notifications(integer) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.api_mark_notification_read(bigint) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.api_my_notifications(integer) TO authenticated;
GRANT EXECUTE ON FUNCTION public.api_mark_notification_read(bigint) TO authenticated;

COMMIT;

drop policy if exists profiles_read_self_or_dispatcher on public.profiles;
create policy profiles_read_self_or_dispatcher on public.profiles for select to authenticated
using (auth_user_id = auth.uid() or public.tacresq_actor_role() = 'dispatcher');
drop policy if exists profiles_update_self on public.profiles;
create policy profiles_update_self on public.profiles for update to authenticated
using (auth_user_id = auth.uid() and role in ('responder','driver'))
with check (auth_user_id = auth.uid() and role in ('responder','driver'));

drop policy if exists incidents_read_participant_or_dispatcher on public.incidents;
create policy incidents_read_participant_or_dispatcher on public.incidents for select to authenticated
using (requester_id in (select id from public.profiles where auth_user_id = auth.uid())
  or assigned_to in (select id from public.profiles where auth_user_id = auth.uid())
  or public.tacresq_actor_role() = 'dispatcher');
drop policy if exists incidents_insert_requester on public.incidents;
create policy incidents_insert_requester on public.incidents for insert to authenticated
with check (requester_id in (select id from public.profiles where auth_user_id = auth.uid() and role = 'requester') and status = 'pending' and assigned_to is null);
drop policy if exists incidents_update_dispatcher_or_assigned_unit on public.incidents;
create policy incidents_update_dispatcher_or_assigned_unit on public.incidents for update to authenticated
using (public.tacresq_actor_role() = 'dispatcher' or assigned_to in (select id from public.profiles where auth_user_id = auth.uid()))
with check (public.tacresq_actor_role() = 'dispatcher' or assigned_to in (select id from public.profiles where auth_user_id = auth.uid()));

drop policy if exists status_logs_read_participants on public.incident_status_logs;
create policy status_logs_read_participants on public.incident_status_logs for select to authenticated
using (exists(select 1 from public.incidents i join public.profiles p on p.id = i.requester_id where i.id = incident_id and (p.auth_user_id = auth.uid() or i.assigned_to in (select id from public.profiles where auth_user_id = auth.uid()) or public.tacresq_actor_role() = 'dispatcher')));
drop policy if exists location_logs_read_dispatcher_or_owner on public.location_logs;
create policy location_logs_read_dispatcher_or_owner on public.location_logs for select to authenticated
using (user_id in (select id from public.profiles where auth_user_id = auth.uid()) or exists(select 1 from public.profiles me where me.auth_user_id = auth.uid() and me.role = 'dispatcher'));
drop policy if exists location_logs_insert_owner on public.location_logs;
create policy location_logs_insert_owner on public.location_logs for insert to authenticated
with check (user_id in (select id from public.profiles where auth_user_id = auth.uid() and role in ('responder','driver')));

create or replace function public.api_me() returns jsonb language sql stable security invoker set search_path = public, pg_temp as $$
 select jsonb_build_object('id',p.id,'name',p.name,'email',p.email,'phone',p.phone,'role',p.role,'duty_status',p.duty_status)
 from public.profiles p where p.auth_user_id = auth.uid();
$$;
create or replace function public.api_my_incidents() returns jsonb language sql stable security invoker set search_path = public, pg_temp as $$
 select coalesce(jsonb_agg(jsonb_build_object('id',i.id,'type',i.type,'description',i.description,'latitude',i.latitude,'longitude',i.longitude,'accuracy_m',i.accuracy_m,'status',i.status,'requester_name',r.name,'requester_phone',r.phone,'assigned_to',i.assigned_to,'created_at',i.created_at) order by i.created_at desc),'[]'::jsonb)
 from public.incidents i join public.profiles r on r.id=i.requester_id
 where i.requester_id in (select id from public.profiles where auth_user_id=auth.uid()) or i.assigned_to in (select id from public.profiles where auth_user_id=auth.uid());
$$;
create or replace function public.api_all_incidents() returns jsonb language plpgsql stable security invoker set search_path = public, pg_temp as $$
begin
 if not exists(select 1 from public.profiles where auth_user_id=auth.uid() and role='dispatcher') then raise exception 'Only dispatchers can view the queue' using errcode='42501'; end if;
 return (select coalesce(jsonb_agg(jsonb_build_object('id',i.id,'type',i.type,'description',i.description,'latitude',i.latitude,'longitude',i.longitude,'accuracy_m',i.accuracy_m,'status',i.status,'requester_name',r.name,'requester_phone',r.phone,'assigned_to',i.assigned_to,'created_at',i.created_at) order by i.created_at desc),'[]'::jsonb) from public.incidents i join public.profiles r on r.id=i.requester_id);
end $$;
create or replace function public.api_units() returns jsonb language plpgsql stable security definer set search_path = public, auth, pg_temp as $$
begin
 if not exists(select 1 from public.profiles where auth_user_id=auth.uid() and role='dispatcher') then raise exception 'Only dispatchers can view field units' using errcode='42501'; end if;
 return (select coalesce(jsonb_agg(jsonb_build_object('id',id,'name',name,'email',email,'phone',phone,'role',role,'duty_status',duty_status) order by name),'[]'::jsonb) from public.profiles where role in ('responder','driver'));
end $$;
revoke all on function public.api_units() from public, anon;
grant execute on function public.api_units() to authenticated;
create or replace function public.api_set_duty_status(p_duty_status text) returns jsonb language plpgsql security invoker set search_path = public, pg_temp as $$
declare p public.profiles;
begin
 if p_duty_status not in ('available','off_duty') then raise exception 'Duty status may only be set to available or off duty' using errcode='22023'; end if;
 select * into p from public.profiles where auth_user_id=auth.uid() for update;
 if p.role not in ('responder','driver') then raise exception 'Only responders and drivers have a duty status' using errcode='42501'; end if;
 if exists(select 1 from public.incidents where assigned_to=p.id and status in ('assigned','en_route','on_scene','transporting')) then raise exception 'Finish your active incident first' using errcode='22023'; end if;
 update public.profiles set duty_status=p_duty_status,updated_at=now() where id=p.id returning * into p;
 return jsonb_build_object('id',p.id,'name',p.name,'email',p.email,'phone',p.phone,'role',p.role,'duty_status',p.duty_status);
end $$;
create or replace function public.api_create_incident(p_type text,p_description text,p_latitude double precision,p_longitude double precision,p_accuracy_m real) returns jsonb language plpgsql security invoker set search_path = public, pg_temp as $$
declare p public.profiles; i public.incidents;
begin
 select * into p from public.profiles where auth_user_id=auth.uid();
 if p.role <> 'requester' then raise exception 'Only requesters can submit incidents' using errcode='42501'; end if;
 insert into public.incidents(requester_id,type,description,latitude,longitude,accuracy_m) values(p.id,p_type,p_description,p_latitude,p_longitude,p_accuracy_m) returning * into i;
 return jsonb_build_object('id',i.id,'type',i.type,'description',i.description,'latitude',i.latitude,'longitude',i.longitude,'accuracy_m',i.accuracy_m,'status',i.status,'requester_name',p.name,'requester_phone',p.phone,'assigned_to',i.assigned_to,'created_at',i.created_at);
end $$;
create or replace function public.api_update_incident_status(p_id bigint,p_status text) returns jsonb language plpgsql security invoker set search_path = public, pg_temp as $$
declare p public.profiles; i public.incidents; allowed boolean;
begin
 select * into p from public.profiles where auth_user_id=auth.uid();
 select * into i from public.incidents where id=p_id for update;
 if not found then raise exception 'Incident not found' using errcode='P0002'; end if;
 if i.assigned_to <> p.id or p.role not in ('responder','driver') then raise exception 'Incident is not assigned to this field unit' using errcode='42501'; end if;
 allowed := (i.status='assigned' and p_status='en_route') or (i.status='en_route' and p_status='on_scene') or (i.status='on_scene' and p_status in ('transporting','resolved')) or (i.status='transporting' and p_status='resolved');
 if not allowed then raise exception 'Invalid incident status transition' using errcode='22023'; end if;
 update public.incidents set status=p_status where id=i.id returning * into i;
 return jsonb_build_object('id',i.id,'type',i.type,'description',i.description,'latitude',i.latitude,'longitude',i.longitude,'accuracy_m',i.accuracy_m,'status',i.status,'requester_name',(select name from public.profiles where id=i.requester_id),'requester_phone',(select phone from public.profiles where id=i.requester_id),'assigned_to',i.assigned_to,'created_at',i.created_at);
end $$;
create or replace function public.api_assign_incident(p_id bigint,p_user_id bigint) returns jsonb language plpgsql security invoker set search_path = public, pg_temp as $$
declare i public.incidents; u public.profiles;
begin
 if not exists(select 1 from public.profiles where auth_user_id=auth.uid() and role='dispatcher') then raise exception 'Only dispatchers can assign incidents' using errcode='42501'; end if;
 select * into i from public.incidents where id=p_id for update;
 if not found or i.status <> 'pending' then raise exception 'Only pending incidents can be assigned' using errcode='22023'; end if;
 select * into u from public.profiles where id=p_user_id for update;
 if u.role not in ('responder','driver') or u.duty_status <> 'available' or exists(select 1 from public.incidents where assigned_to=u.id and status in ('assigned','en_route','on_scene','transporting')) then raise exception 'Selected unit is not available' using errcode='22023'; end if;
 update public.incidents set status='assigned',assigned_to=u.id where id=i.id returning * into i;
 return jsonb_build_object('id',i.id,'type',i.type,'description',i.description,'latitude',i.latitude,'longitude',i.longitude,'accuracy_m',i.accuracy_m,'status',i.status,'requester_name',(select name from public.profiles where id=i.requester_id),'requester_phone',(select phone from public.profiles where id=i.requester_id),'assigned_to',i.assigned_to,'created_at',i.created_at);
end $$;
create or replace function public.api_record_location(p_latitude double precision,p_longitude double precision,p_accuracy_m real,p_recorded_at timestamptz) returns bigint language plpgsql security invoker set search_path = public, pg_temp as $$
declare uid bigint; result bigint;
begin
 select id into uid from public.profiles where auth_user_id=auth.uid() and role in ('responder','driver');
 if uid is null then raise exception 'Only field units may submit locations' using errcode='42501'; end if;
 insert into public.location_logs(user_id,latitude,longitude,accuracy_m,recorded_at) values(uid,p_latitude,p_longitude,p_accuracy_m,coalesce(p_recorded_at,now())) returning id into result;
 return result;
end $$;


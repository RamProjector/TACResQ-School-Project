-- Supabase project baseline: automatically enable RLS for newly created public tables.
create or replace function public.rls_auto_enable()
returns event_trigger
language plpgsql
security definer
set search_path = pg_catalog
as $function$
declare
  cmd record;
  tbl name;
begin
  for cmd in
    select *
      from pg_event_trigger_ddl_commands()
     where command_tag in ('CREATE TABLE', 'CREATE TABLE AS', 'SELECT INTO')
       and object_type in ('table', 'partitioned table')
  loop
    if cmd.schema_name = 'public'
       and cmd.schema_name not like 'pg_toast%'
       and cmd.schema_name not like 'pg_temp%' then
      begin
        select c.relname into tbl
          from pg_catalog.pg_class c
         where c.oid = cmd.objid;
        execute format('alter table if exists %I.%I enable row level security', cmd.schema_name, tbl);
        raise log 'rls_auto_enable: enabled RLS on %', cmd.object_identity;
      exception when others then
        raise log 'rls_auto_enable: failed to enable RLS on %', cmd.object_identity;
      end;
    else
      raise log 'rls_auto_enable: skip % (schema: %)', cmd.object_identity, cmd.schema_name;
    end if;
  end loop;
end;
$function$;

drop event trigger if exists ensure_rls;
create event trigger ensure_rls
  on ddl_command_end
  execute function public.rls_auto_enable();

create table if not exists public.profiles (
  id bigint generated by default as identity primary key,
  auth_user_id uuid not null unique references auth.users(id) on delete cascade,
  name text not null check (length(trim(name)) between 1 and 120),
  email text not null unique,
  phone text,
  role text not null default 'requester' check (role in ('requester','responder','driver','dispatcher')),
  duty_status text check (duty_status in ('off_duty','available','en_route','on_scene','transporting')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((role in ('responder','driver') and duty_status is not null) or (role in ('requester','dispatcher') and duty_status is null))
);

create table if not exists public.incidents (
  id bigint generated by default as identity primary key,
  requester_id bigint not null references public.profiles(id),
  type text not null check (type in ('medical','fire','vehicular','disaster','other')),
  description text check (description is null or length(description) <= 2000),
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  accuracy_m real check (accuracy_m is null or accuracy_m >= 0),
  status text not null default 'pending' check (status in ('pending','assigned','en_route','on_scene','transporting','resolved','cancelled')),
  assigned_to bigint references public.profiles(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((status = 'pending' and assigned_to is null) or (status <> 'pending' and status <> 'cancelled' and assigned_to is not null) or status = 'cancelled')
);

create table if not exists public.incident_status_logs (
  id bigint generated by default as identity primary key,
  incident_id bigint not null references public.incidents(id) on delete cascade,
  status text not null check (status in ('pending','assigned','en_route','on_scene','transporting','resolved','cancelled')),
  changed_by bigint references public.profiles(id),
  created_at timestamptz not null default now()
);

create table if not exists public.location_logs (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.profiles(id) on delete cascade,
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  accuracy_m real check (accuracy_m is null or accuracy_m >= 0),
  recorded_at timestamptz not null default now()
);

create index if not exists incidents_requester_created_idx on public.incidents (requester_id, created_at desc);
create index if not exists incidents_assigned_created_idx on public.incidents (assigned_to, created_at desc);
create index if not exists incidents_queue_created_idx on public.incidents (status, created_at desc);
create index if not exists location_logs_user_recorded_idx on public.location_logs (user_id, recorded_at desc);

create or replace function public.tacresq_profile_on_signup()
returns trigger language plpgsql security definer set search_path = public, auth, pg_temp as $$
declare
  requested_role text;
begin
  requested_role := coalesce(new.raw_user_meta_data ->> 'role', 'requester');
  -- Public sign-up can only create requesters; privileged roles are provisioned by an administrator.
  if requested_role <> 'requester' then requested_role := 'requester'; end if;
  insert into public.profiles(auth_user_id, name, email, phone, role, duty_status)
  values (new.id, coalesce(nullif(trim(new.raw_user_meta_data ->> 'name'), ''), split_part(new.email, '@', 1)),
          lower(new.email), nullif(trim(new.raw_user_meta_data ->> 'phone'), ''), requested_role, null)
  on conflict (auth_user_id) do nothing;
  return new;
end;
$$;
revoke all on function public.tacresq_profile_on_signup() from public, anon, authenticated;
drop trigger if exists tacresq_auth_user_created on auth.users;
create trigger tacresq_auth_user_created after insert on auth.users
for each row execute function public.tacresq_profile_on_signup();

create or replace function public.tacresq_log_incident_status()
returns trigger language plpgsql security definer set search_path = public, auth, pg_temp as $$
declare actor_id bigint;
begin
  if tg_op = 'INSERT' then
    insert into public.incident_status_logs(incident_id,status,changed_by) values(new.id,new.status,new.requester_id);
  elsif new.status is distinct from old.status then
    select id into actor_id from public.profiles where auth_user_id = auth.uid();
    insert into public.incident_status_logs(incident_id,status,changed_by) values(new.id,new.status,actor_id);
    if new.assigned_to is not null and new.status in ('en_route','on_scene','transporting','resolved') then
      update public.profiles set duty_status = case new.status when 'resolved' then 'available' else new.status end, updated_at = now()
       where id = new.assigned_to;
    end if;
  end if;
  new.updated_at := now();
  return new;
end;
$$;
revoke all on function public.tacresq_log_incident_status() from public, anon, authenticated;
drop trigger if exists tacresq_incident_status_audit on public.incidents;
create trigger tacresq_incident_status_audit before insert or update on public.incidents
for each row execute function public.tacresq_log_incident_status();

-- Safe, narrowly scoped helper avoids recursive RLS lookups on profiles.
create or replace function public.tacresq_actor_role() returns text
language sql stable security definer set search_path = public, auth, pg_temp as $$
 select role from public.profiles where auth_user_id = auth.uid();
$$;
revoke all on function public.tacresq_actor_role() from public, anon;
grant execute on function public.tacresq_actor_role() to authenticated;

create or replace function public.tacresq_guard_incident_update()
returns trigger language plpgsql security definer set search_path = public, auth, pg_temp as $$
declare actor_role text; actor_id bigint; unit_status text;
begin
 select role,id into actor_role,actor_id from public.profiles where auth_user_id=auth.uid();
 if new.assigned_to is distinct from old.assigned_to then
   select duty_status into unit_status from public.profiles where id=new.assigned_to;
   if actor_role <> 'dispatcher' or old.status <> 'pending' or new.status <> 'assigned' or unit_status <> 'available' then
     raise exception 'Only a dispatcher may assign a pending incident to an available unit' using errcode='42501';
   end if;
 end if;
 if new.status is distinct from old.status then
   if new.status='assigned' then
     if actor_role <> 'dispatcher' or old.status <> 'pending' or new.assigned_to is null then raise exception 'Invalid assignment' using errcode='42501'; end if;
   elsif actor_id <> old.assigned_to or actor_role not in ('responder','driver') or not (
       (old.status='assigned' and new.status='en_route') or
       (old.status='en_route' and new.status='on_scene') or
       (old.status='on_scene' and new.status in ('transporting','resolved')) or
       (old.status='transporting' and new.status='resolved')) then
     raise exception 'Invalid incident status transition' using errcode='42501';
   end if;
 end if;
 return new;
end $$;
revoke all on function public.tacresq_guard_incident_update() from public, anon, authenticated;
drop trigger if exists tacresq_guard_incident_update_trigger on public.incidents;
create trigger tacresq_guard_incident_update_trigger before update on public.incidents
for each row execute function public.tacresq_guard_incident_update();

create or replace function public.tacresq_guard_profile_update()
returns trigger language plpgsql security definer set search_path = public, auth, pg_temp as $$
begin
 if auth.uid() is not null and pg_trigger_depth() = 1 then
   if new.auth_user_id is distinct from old.auth_user_id or new.role is distinct from old.role or
      new.name is distinct from old.name or new.email is distinct from old.email or new.phone is distinct from old.phone then
     raise exception 'Profile identity and role fields cannot be changed by the mobile client' using errcode='42501';
   end if;
   if new.duty_status not in ('available','off_duty') then raise exception 'Invalid user-set duty status' using errcode='22023'; end if;
   if exists(select 1 from public.incidents where assigned_to=old.id and status in ('assigned','en_route','on_scene','transporting')) then
     raise exception 'Finish your active incident first' using errcode='22023';
   end if;
 end if;
 new.updated_at := now();
 return new;
end $$;
revoke all on function public.tacresq_guard_profile_update() from public, anon, authenticated;
drop trigger if exists tacresq_guard_profile_update_trigger on public.profiles;
create trigger tacresq_guard_profile_update_trigger before update on public.profiles
for each row execute function public.tacresq_guard_profile_update();


-- FCM token storage and authenticated self-service registration.
-- This migration is part of the baseline history already applied to the TACResQ project.

create table if not exists public.fcm_tokens (
  id bigint generated by default as identity primary key,
  profile_id bigint not null references public.profiles(id) on delete cascade,
  token text not null unique
    constraint fcm_tokens_token_check check (length(token) >= 20 and length(token) <= 4096),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists fcm_tokens_profile_idx
  on public.fcm_tokens(profile_id);

alter table public.fcm_tokens enable row level security;

drop policy if exists fcm_tokens_self on public.fcm_tokens;
create policy fcm_tokens_self
  on public.fcm_tokens for select to authenticated
  using (profile_id in (
    select id from public.profiles
    where auth_user_id = (select auth.uid())
  ));

drop policy if exists fcm_tokens_insert_self on public.fcm_tokens;
create policy fcm_tokens_insert_self
  on public.fcm_tokens for insert to authenticated
  with check (profile_id in (
    select id from public.profiles
    where auth_user_id = (select auth.uid())
  ));

drop policy if exists fcm_tokens_delete_self on public.fcm_tokens;
create policy fcm_tokens_delete_self
  on public.fcm_tokens for delete to authenticated
  using (profile_id in (
    select id from public.profiles
    where auth_user_id = (select auth.uid())
  ));

grant usage on schema public to authenticated;
grant select, insert, update, delete on public.fcm_tokens to authenticated;
grant usage, select on sequence public.fcm_tokens_id_seq to authenticated;

create or replace function public.api_register_fcm_token(p_token text)
returns void
language plpgsql
security invoker
set search_path = public, pg_temp
as $function$
declare
  profile bigint;
begin
  if p_token is null or length(p_token) < 20 or length(p_token) > 4096 then
    raise exception 'Invalid FCM token' using errcode = '22023';
  end if;

  select id into profile
    from public.profiles
   where auth_user_id = auth.uid();

  if profile is null then
    raise exception 'Profile not found' using errcode = '42501';
  end if;

  delete from public.fcm_tokens
   where profile_id = profile and token = p_token;

  insert into public.fcm_tokens(profile_id, token)
  values (profile, p_token);
end;
$function$;

create or replace function public.api_unregister_fcm_token(p_token text)
returns void
language plpgsql
security invoker
set search_path = public, pg_temp
as $function$
declare
  profile bigint;
begin
  select id into profile
    from public.profiles
   where auth_user_id = auth.uid();

  delete from public.fcm_tokens
   where profile_id = profile and token = p_token;
end;
$function$;

revoke all on function public.api_register_fcm_token(text) from public, anon;
grant execute on function public.api_register_fcm_token(text) to authenticated;

revoke all on function public.api_unregister_fcm_token(text) from public, anon;
grant execute on function public.api_unregister_fcm_token(text) to authenticated;

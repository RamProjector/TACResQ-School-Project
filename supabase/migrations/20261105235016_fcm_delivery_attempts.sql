BEGIN;

-- Server-only ledger used by the trusted FCM worker. It prevents a polling
-- worker from repeatedly sending the same notification/token pair while keeping
-- the existing user_notifications inbox as the source of truth.
CREATE TABLE IF NOT EXISTS public.fcm_delivery_attempts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  notification_id bigint NOT NULL REFERENCES public.user_notifications(id) ON DELETE CASCADE,
  profile_id bigint NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  token text NOT NULL,
  status text NOT NULL CHECK (status IN ('claimed', 'sent', 'invalid_token', 'failed')),
  provider_message_name text,
  last_error_code text,
  attempted_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (notification_id, token)
);

CREATE INDEX IF NOT EXISTS fcm_delivery_attempts_notification_idx
  ON public.fcm_delivery_attempts (notification_id, updated_at DESC);

-- No client role may read, insert, update, or delete delivery attempts.
-- The trusted server uses the Supabase service-role key, which bypasses RLS.
ALTER TABLE public.fcm_delivery_attempts ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.fcm_delivery_attempts FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.fcm_delivery_attempts_id_seq FROM PUBLIC, anon, authenticated;

COMMIT;
